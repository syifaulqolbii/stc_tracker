#!/usr/bin/env bash
# Menghasilkan SQL bootstrap dc_schema dari file schema di root repo.
set -euo pipefail
cd "$(dirname "$0")/.."
out="${1:--}"

files=(
  schema-v1-2.sql schema-multi-group.sql schema-reminder.sql schema-solver-contacts.sql
  schema-media-columns.sql schema-migration-deleted-at.sql schema-migration-author-name.sql
  schema-migration-group-default.sql seed-v1-2.sql
)

emit() {
  printf -- '-- generated by scripts/build-db-bootstrap.sh — jangan diedit manual\n'
  printf 'SET search_path TO dc_schema;\nBEGIN;\n\n'
  for f in "${files[@]}"; do
    printf -- '-- ===== %s\n' "$f"
    # Normalkan CRLF -> LF: beberapa file schema tersimpan CRLF di checkout Windows,
    # dan itu membuat sha256 db-bootstrap.sql berbeda antar-mesin.
    sed 's/\r$//' "$f"; printf '\n\n'
  done
  cat <<'SQL'
-- alert_state: dulu dibuat runtime oleh app; di sini agar role aplikasi tidak butuh CREATE
CREATE TABLE IF NOT EXISTS alert_state (
  service             TEXT PRIMARY KEY,
  state               TEXT NOT NULL DEFAULT 'ok',
  detail              TEXT,
  first_seen_down_at  TIMESTAMPTZ,
  last_alert_at       TIMESTAMPTZ,
  last_ok_at          TIMESTAMPTZ,
  alert_count         INT NOT NULL DEFAULT 0,
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMIT;
SQL
}

if [[ "$out" == "-" ]]; then emit; else emit > "$out"; echo "wrote $out"; fi
